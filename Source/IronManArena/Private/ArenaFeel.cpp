UArenaFeelSubsystem* UArenaFeelSubsystem::Get(const UObject* WorldContext)
{
	const UWorld* World = WorldContext ? WorldContext->GetWorld() : nullptr;
	return World ? World->GetSubsystem<UArenaFeelSubsystem>() : nullptr;
}

bool UArenaFeelSubsystem::DoesSupportWorldType(const EWorldType::Type WorldType) const
{
	return WorldType == EWorldType::Game || WorldType == EWorldType::PIE;
}

TStatId UArenaFeelSubsystem::GetStatId() const
{
	RETURN_QUICK_DECLARE_CYCLE_STAT(UArenaFeelSubsystem, STATGROUP_Tickables);
}

bool UArenaFeelSubsystem::ShakeAllowed() const
{
	const UArenaGameUserSettings* S = UArenaGameUserSettings::GetArenaSettings();
	return !S || S->bCameraShake; // reduced motion = 0.35x via GetShakeIntensity (camera_shake.json presets.reduced)
}

float UArenaFeelSubsystem::GetStackDilation() const
{
	float MinVal = 1.f;
	for (const TPair<FName, float>& Pair : DilationStack)
	{
		MinVal = FMath::Min(MinVal, Pair.Value);
	}
	return MinVal;
}

void UArenaFeelSubsystem::ApplyDilation()
{
	UWorld* World = GetWorld();
	if (!World) { return; }
	float Target = GetStackDilation();
	if (HitStopLeft > 0.f)
	{
		Target = FMath::Min(Target, HitStopDilation);
	}
	Target = FMath::Clamp(Target, 0.0001f, 20.f);
	AppliedDilation = Target;
	UGameplayStatics::SetGlobalTimeDilation(World, Target);
}

void UArenaFeelSubsystem::PushDilation(FName Source, float Value)
{
	if (Source.IsNone()) { return; }
	DilationStack.Add(Source, FMath::Clamp(Value, 0.0001f, 20.f));
	ApplyDilation();
}

void UArenaFeelSubsystem::PopDilation(FName Source)
{
	if (Source.IsNone()) { return; }
	DilationStack.Remove(Source);
	ApplyDilation();
}

void UArenaFeelSubsystem::HitStop(float RealSeconds, float Dilation)
{
	if (CVarHitStop.GetValueOnGameThread() == 0 || RealSeconds <= 0.f) { return; }
	const UArenaGameUserSettings* S = UArenaGameUserSettings::GetArenaSettings();
	if (S && S->bHudReducedMotion) { RealSeconds *= 0.5f; } // shorter freeze for motion-sensitive players
	const bool bWasHitStopping = HitStopLeft > 0.f;
	HitStopLeft = FMath::Max(HitStopLeft, FMath::Min(RealSeconds, 0.3f));
	HitStopDilation = FMath::Clamp(FMath::Min(bWasHitStopping ? HitStopDilation : 1.f, Dilation), 0.02f, 1.f);
	ApplyDilation();
}

void UArenaFeelSubsystem::AddTrauma(float Amount)
{
	Trauma = FMath::Clamp(Trauma + Amount, 0.f, 1.f);
}

void UArenaFeelSubsystem::AddBlastTrauma(const FVector& Location, float Radius)
{
	if (Radius <= 0.f) { return; }
	// Epicenter + radius go to the Vison explosion shake (inner R, outer 6R + 400 cm, exponent 1.6).
	PlayShake(TEXT("explosion_nearby"), 1.f, &Location, Radius);
}

// ------------------------------------------------------------------------------------------------
// Vison shake profiles (Content/Story/camera_shake.json, generated by contrib/vison/camera/gen_camera_realism.py)
// ------------------------------------------------------------------------------------------------
namespace ArenaShakeData
{
	// Axis order: X, Y, Z (cm, camera local), Pitch, Yaw, Roll (deg)
	struct FAxis { float Amp = 0.f; float Hz = 0.f; bool bWave = false; };
	struct FProfile
	{
		FAxis Axes[6];
		float TraumaRef = 0.3f;
		float FirstPersonRot = 0.6f;
		bool bCutsceneOnly = false;
	};

	static const TCHAR* AxisNames[6] = { TEXT("X"), TEXT("Y"), TEXT("Z"), TEXT("Pitch"), TEXT("Yaw"), TEXT("Roll") };

	// Cutscene-only per the camera decisions (#9 supersonic: flight tops out ~29 m/s; handheld = StoryDirector).
	static bool CutsceneOnlyId(const FString& Id)
	{
		return Id == TEXT("supersonic_flight") || Id == TEXT("handheld_cutscene");
	}

	static const TMap<FName, FProfile>& Profiles()
	{
		static TMap<FName, FProfile> Map;
		static bool bLoaded = false;
		if (bLoaded) { return Map; }
		bLoaded = true;
		FString Text;
		const FString Path = FPaths::ProjectContentDir() / TEXT("Story/camera_shake.json");
		TSharedPtr<FJsonObject> Root;
		if (!FFileHelper::LoadFileToString(Text, *Path)) { return Map; }
		const TSharedRef<TJsonReader<>> Reader = TJsonReaderFactory<>::Create(Text);
		if (!FJsonSerializer::Deserialize(Reader, Root) || !Root.IsValid()) { return Map; }
		const TSharedPtr<FJsonObject>* Shakes = nullptr;
		if (!Root->TryGetObjectField(TEXT("shakes"), Shakes)) { return Map; }
		for (const auto& Pair : (*Shakes)->Values)
		{
			const FString Key(*Pair.Key);
			const TSharedPtr<FJsonObject> Obj = Pair.Value.IsValid() ? Pair.Value->AsObject() : nullptr;
			if (!Obj.IsValid()) { continue; }
			FProfile P;
			double D = 0.0;
			if (Obj->TryGetNumberField(TEXT("arenafeel_trauma_equivalent"), D)) { P.TraumaRef = FMath::Clamp(float(D), 0.05f, 1.f); }
			if (Obj->TryGetNumberField(TEXT("first_person_rotation_scale"), D)) { P.FirstPersonRot = float(D); }
			FString Trigger;
			Obj->TryGetStringField(TEXT("trigger"), Trigger);
			P.bCutsceneOnly = CutsceneOnlyId(Key) || Trigger.Contains(TEXT("cutscene only"));
			const TArray<TSharedPtr<FJsonValue>>* Patterns = nullptr;
			if (Obj->TryGetArrayField(TEXT("patterns"), Patterns))
			{
				// Several patterns (e.g. a hit + a rumble): per axis keep the strongest one.
				for (const TSharedPtr<FJsonValue>& PV : *Patterns)
				{
					const TSharedPtr<FJsonObject> Pat = PV.IsValid() ? PV->AsObject() : nullptr;
					const TSharedPtr<FJsonObject>* AxesObj = nullptr;
					if (!Pat.IsValid() || !Pat->TryGetObjectField(TEXT("axes"), AxesObj)) { continue; }
					FString Type;
					Pat->TryGetStringField(TEXT("type"), Type);
					for (int32 A = 0; A < 6; ++A)
					{
						const TSharedPtr<FJsonObject>* Ax = nullptr;
						if (!(*AxesObj)->TryGetObjectField(AxisNames[A], Ax)) { continue; }
						double Amp = 0.0, Hz = 0.0;
						(*Ax)->TryGetNumberField(TEXT("Amplitude"), Amp);
						(*Ax)->TryGetNumberField(TEXT("Frequency_hz"), Hz);
						if (FMath::Abs(float(Amp)) > FMath::Abs(P.Axes[A].Amp))
						{
							P.Axes[A].Amp = float(Amp);
							P.Axes[A].Hz = FMath::Clamp(float(Hz), 0.05f, 30.f); // camera_notes: <= 20 Hz (unibeam 30)
							P.Axes[A].bWave = Type.Contains(TEXT("Wave"));
						}
					}
				}
			}
			Map.Add(FName(*Key), P);
		}
		UE_LOG(LogTemp, Log, TEXT("ArenaFeel: %d camera shake profiles from %s"), Map.Num(), *Path);
		return Map;
	}
}

int32 UArenaFeelSubsystem::NumShakeProfiles() const { return ArenaShakeData::Profiles().Num(); }

bool UArenaFeelSubsystem::IsCutsceneOnlyShake(FName Id)
{
	const ArenaShakeData::FProfile* P = ArenaShakeData::Profiles().Find(Id);
	return P && P->bCutsceneOnly;
}

float UArenaFeelSubsystem::GetShakeIntensity()
{
	float K = CVarShakeScale.GetValueOnGameThread();
	if (const UArenaGameUserSettings* S = UArenaGameUserSettings::GetArenaSettings())
	{
		if (!S->bCameraShake) { return 0.f; }
		K *= FMath::Clamp(S->CameraShakeIntensity, 0.f, 1.5f);
		if (S->bHudReducedMotion) { K *= 0.35f; } // camera_shake.json accessibility.presets.reduced
	}
	return FMath::Max(0.f, K);
}

bool UArenaFeelSubsystem::PlayShake(FName Id, float Scale, const FVector* Epicenter, float InnerRadius)
{
	const ArenaShakeData::FProfile* P = ArenaShakeData::Profiles().Find(Id);
	float Falloff = 1.f;
	if (Epicenter)
	{
		const UWorld* World = GetWorld();
		const APawn* Pawn = World ? UGameplayStatics::GetPlayerPawn(World, 0) : nullptr;
		if (!Pawn) { return false; }
		const float R = FMath::Max(InnerRadius, 1.f);
		const float Outer = R * 6.f + 400.f;
		const float Dist = float(FVector::Dist(Pawn->GetActorLocation(), *Epicenter));
		if (Dist >= Outer) { return false; }
		Falloff = Dist <= R ? 1.f : FMath::Pow(1.f - (Dist - R) / (Outer - R), 1.6f);
		Scale *= FMath::Clamp(R / 400.f, 0.1f, 1.f); // a grenade is not a titan slam
	}
	if (!P)
	{
		// No json (or unknown id): the built-in trauma noise still works.
		AddTrauma(0.3f * Scale * Falloff);
		return false;
	}
	if (P->bCutsceneOnly) { return false; }
	const float Add = P->TraumaRef * Scale * Falloff;
	// The stronger request owns the profile; a light hit doesn't swap out an explosion mid-shake.
	if (Add >= Trauma * 0.7f || ActiveShake.IsNone())
	{
		ActiveShake = Id;
		ActiveTraumaRef = P->TraumaRef;
	}
	AddTrauma(Add);
	return true;
}

void UArenaFeelSubsystem::GetShake(FRotator& OutRot, FVector& OutLoc) const
{
	OutRot = FRotator::ZeroRotator;
	OutLoc = FVector::ZeroVector;
	if (Trauma <= 0.f || !ShakeAllowed() || bCinematicCamera) { return; }
	const float K = GetShakeIntensity();
	if (K <= 0.f) { return; }
	const ArenaShakeData::FProfile* P = ActiveShake.IsNone() ? nullptr : ArenaShakeData::Profiles().Find(ActiveShake);
	if (P)
	{
		// Vison profile in real units, amplitude = peak x (trauma / its reference)^2 (capped at 1.5x).
		const float Env = FMath::Min(FMath::Square(Trauma / FMath::Max(ActiveTraumaRef, 0.05f)), 1.5f) * K;
		const float T = float(ShakeClock);
		float V[6];
		for (int32 A = 0; A < 6; ++A)
		{
			const ArenaShakeData::FAxis& Ax = P->Axes[A];
			if (Ax.Amp == 0.f) { V[A] = 0.f; continue; }
			// Same conventions as UE's shake patterns (verified in 5.8 source): wave = sin(2 pi Hz t);
			// Perlin lattice ~0.6 cycles per unit, so units = Hz / 0.6 (camera_shake.json ue_unit_conversion).
			const float Phase = Ax.bWave ? T * Ax.Hz : T * Ax.Hz / 0.6f;
			V[A] = Ax.Amp * Env * (Ax.bWave ? FMath::Sin(2.f * PI * Phase + A * 1.7f)
				: FMath::Clamp(FMath::PerlinNoise1D(Phase + 13.7f * (A + 1)) * 1.6f, -1.f, 1.f));
		}
		OutLoc = FVector(V[0], V[1], V[2]);
		OutRot = FRotator(V[3], V[4], V[5]);
		return;
	}
	const float A = Trauma * Trauma * K;
	const float T = float(ShakeClock) * 22.f;
	OutRot.Pitch = A * 2.4f * FMath::PerlinNoise1D(T + 11.3f);
	OutRot.Yaw = A * 2.4f * FMath::PerlinNoise1D(T + 47.1f);
	OutRot.Roll = A * 3.0f * FMath::PerlinNoise1D(T + 83.7f);
	OutLoc = FVector(0.f, FMath::PerlinNoise1D(T + 5.f), FMath::PerlinNoise1D(T + 9.f)) * (A * 6.f);
}

void UArenaFeelSubsystem::Tick(float DeltaTime)
{
	// Real (undilated) time so the freeze lasts the same however hard it slows the game.
	const float RealDt = FMath::Min(float(FApp::GetDeltaTime()), 0.1f);
	ShakeClock += RealDt;
	Trauma = FMath::Max(0.f, Trauma - 1.6f * RealDt);
	if (Trauma <= 0.f) { ActiveShake = NAME_None; }
	if (HitStopLeft > 0.f)
	{
		UWorld* World = GetWorld();
		const float Now = World ? UGameplayStatics::GetGlobalTimeDilation(World) : AppliedDilation;
		if (!FMath::IsNearlyEqual(Now, AppliedDilation, 0.001f))
		{
			// External owner (autopilot / legacy SetGlobalTimeDilation): abandon the freeze and resync.
			HitStopLeft = 0.f;
			HitStopDilation = 1.f;
			AppliedDilation = Now;
		}
		else
		{
			HitStopLeft -= RealDt;
			if (HitStopLeft <= 0.f)
			{
				HitStopLeft = 0.f;
				HitStopDilation = 1.f;
				ApplyDilation(); // B01: restore to stack (suit wheel etc.), not hard 1.0
			}
		}
	}
}

void UArenaFeelSubsystem::Deinitialize()
{
	DilationStack.Empty();
	HitStopLeft = 0.f;
	HitStopDilation = 1.f;
	if (UWorld* World = GetWorld()) { UGameplayStatics::SetGlobalTimeDilation(World, 1.f); }
	AppliedDilation = 1.f;
	Super::Deinitialize();
}

