"""
Downloads the free CC0 textures + HDRI used by the realistic materials from Poly Haven
(https://polyhaven.com, CC0 1.0 - public domain, no login, redistribution allowed) into
SourceAssets/PolyHaven/<asset>/ at 2K. Then run Content/Python/import_cc0_textures.py in the
editor (headless: see Docs/REALISM.md) to turn them into /Game/Realism/Textures/... assets.

    python3 Tools/fetch_cc0_assets.py            # downloads what is missing
    python3 Tools/fetch_cc0_assets.py --list     # only prints the plan + sizes

Attribution is written to Docs/CREDITS.md (not required by CC0, but good manners).
"""
import json, os, sys, hashlib, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "SourceAssets", "PolyHaven")
UA = {"User-Agent": "IronManArena-asset-fetch/1.0 (CC0 texture import script)"}

# asset id -> what it is used for (key = material slot in import_cc0_textures.py)
TEXTURES = {
    "garage_floor":        "workshop floor (Tony's lake-house garage)",
    "asphalt_02":          "city streets",
    "brushed_concrete":    "rooftops / concrete",
    "concrete_block_wall": "building walls",
    "brick_wall_001":      "city building walls (variety)",
    "metal_plate":         "workshop props, Hall of Armor plinths, robot arms",
    "rusty_metal_02":      "ruins props, wrecked vehicles",
    "rubble":              "ruins ground",
    "burned_ground_01":    "Titan's battlefield ground",
}
MAPS = {"Diffuse": "diff", "nor_dx": "nor_dx", "arm": "arm"}  # arm = AO / Roughness / Metallic packed
HDRIS = {
    "industrial_sunset_02_puresky": "sky / reflection fallback for outdoor chapters",
}
RES = "2k"


def get_json(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return json.load(r)


def plan():
    items = []
    for asset, use in TEXTURES.items():
        files = get_json("https://api.polyhaven.com/files/" + asset)
        for key, short in MAPS.items():
            f = files.get(key, {}).get(RES, {})
            f = f.get("jpg") or f.get("png")
            if not f:
                print("  (no %s %s for %s)" % (RES, key, asset))
                continue
            ext = os.path.splitext(f["url"])[1]
            items.append((asset, use, os.path.join(OUT, asset, "%s_%s_%s%s" % (asset, short, RES, ext)), f))
    for asset, use in HDRIS.items():
        files = get_json("https://api.polyhaven.com/files/" + asset)
        f = files.get("hdri", {}).get(RES, {}).get("hdr")
        if f:
            items.append((asset, use, os.path.join(OUT, "hdri", "%s_%s.hdr" % (asset, RES)), f))
    return items


def md5(path):
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_credits():
    path = os.path.join(ROOT, "Docs", "CREDITS.md")
    lines = [
        "# Credits",
        "",
        "## Textures and HDRIs - Poly Haven (CC0 1.0)",
        "",
        "Downloaded by `Tools/fetch_cc0_assets.py` from https://polyhaven.com at 2K and imported by",
        "`Content/Python/import_cc0_textures.py`. CC0 = public domain dedication: free to use, modify and",
        "redistribute, no attribution required. Credited anyway, with thanks.",
        "",
        "| Asset | Used for | Source |",
        "|---|---|---|",
    ]
    for asset, use in list(TEXTURES.items()) + list(HDRIS.items()):
        lines.append("| %s | %s | https://polyhaven.com/a/%s |" % (asset, use, asset))
    lines += [
        "",
        "## Engine content",
        "",
        "- UE5 Manny / Quinn mannequins, engine basic shapes and materials: Epic Games, used under the",
        "  Unreal Engine EULA (engine content, redistributable inside Unreal Engine projects).",
        "",
        "## Voices",
        "",
        "- All voice lines are generated by `Tools/generate_suits_and_voices.py` / `Tools/generate_story_audio.py`",
        "  (offline TTS on the build box); no third-party recordings.",
        "",
        "Iron Man, Vision and related names are Marvel characters; this is a non-commercial fan project.",
        "",
    ]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def main():
    items = plan()
    total = sum(f["size"] for _, _, _, f in items)
    print("%d files, %.1f MB" % (len(items), total / 1e6))
    if "--list" in sys.argv:
        for asset, use, path, f in items:
            print("  %-60s %6.1f MB" % (os.path.relpath(path, ROOT), f["size"] / 1e6))
        return
    for asset, use, path, f in items:
        if os.path.exists(path) and md5(path) == f["md5"]:
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        print("  get", os.path.relpath(path, ROOT))
        with urllib.request.urlopen(urllib.request.Request(f["url"], headers=UA), timeout=300) as r, open(path, "wb") as out:
            out.write(r.read())
        if md5(path) != f["md5"]:
            raise SystemExit("md5 mismatch for " + path)
    write_credits()
    print("done; credits in Docs/CREDITS.md")


if __name__ == "__main__":
    main()
