#!/usr/bin/env python3
"""Controls reference generator / checker (Vison, menu lane).

Source of truth: controls_bindings.json (keys read from the C++ source, nothing invented).

  python3 gen_controls_table.py --check     # verify every key name against the cited source file
  python3 gen_controls_table.py             # --check, then write ControlsReference.inl next to this script

The generated ControlsReference.inl already lives at Source/IronManArena/Private/Generated/.
This script never writes outside its folder; copy the result into Private/Generated/ if you regenerate.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_SRC = os.path.normpath(os.path.join(HERE, "..", "..", "Source", "IronManArena"))
JSON_PATH = os.path.join(HERE, "controls_bindings.json")
OUT_PATH = os.path.join(HERE, "ControlsReference.inl")


def cpp_str(s):
    return 'TEXT("' + s.replace("\\", "\\\\").replace('"', '\\"') + '")'


def check(data, src_root):
    errors = []
    cache = {}
    rows = [r for g in data["groups"] for r in g["rows"]] + data.get("not_listed_to_players", [])
    for r in rows:
        path = os.path.join(src_root, r["source"])
        if path not in cache:
            if not os.path.isfile(path):
                errors.append("%s: source file missing (%s)" % (r["action"], r["source"]))
                cache[path] = ""
                continue
            with open(path, encoding="utf-8", errors="replace") as f:
                cache[path] = f.read()
        text = cache[path]
        for k in r.get("kbm_keys", []) + r.get("pad_keys", []):
            if not re.search(r"EKeys::%s\b" % re.escape(k), text):
                errors.append("%s: EKeys::%s not found in %s" % (r["action"], k, r["source"]))
        if r.get("rebind_name"):
            pat = r'Key\(TEXT\("%s"\),\s*EKeys::%s\)' % (re.escape(r["rebind_name"]), re.escape(r["rebind_default"]))
            if not re.search(pat, text):
                errors.append("%s: rebindable Key(\"%s\", %s) not found in %s" % (r["action"], r["rebind_name"], r["rebind_default"], r["source"]))
    return errors


def reserved_keys(data):
    keys = []
    rows = [r for g in data["groups"] for r in g["rows"]] + data.get("not_listed_to_players", [])
    for r in rows:
        for k in r.get("kbm_keys", []):
            if k not in keys:
                keys.append(k)
    return keys


def emit(data):
    out = [
        "// GENERATED by Tools/vison_menu/gen_controls_table.py from controls_bindings.json - do not edit by hand.",
        "// Included by SettingsWidget.cpp with CONTROLS_GROUP / CONTROLS_ROW / CONTROLS_RESERVED_KEY defined.",
        "// CONTROLS_ROW(Action, KeyboardMouse, Gamepad, Note, RebindName, RebindDefaultKey)",
        "",
    ]
    for g in data["groups"]:
        out.append("CONTROLS_GROUP(%s)" % cpp_str(g["title"]))
        for r in g["rows"]:
            out.append("CONTROLS_ROW(%s, %s, %s, %s, %s, %s)" % (
                cpp_str(r["action"]), cpp_str(r["kbm"]), cpp_str(r["pad"]), cpp_str(r.get("note", "")),
                cpp_str(r.get("rebind_name", "")), cpp_str(r.get("rebind_default", ""))))
        out.append("")
    out.append("// Keyboard / mouse keys already used anywhere (rebinding refuses these unless it is the row's own key).")
    for k in reserved_keys(data):
        out.append("CONTROLS_RESERVED_KEY(%s)" % cpp_str(k))
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only validate against the source")
    ap.add_argument("--src", default=REPO_SRC, help="Source/IronManArena folder")
    a = ap.parse_args()
    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f)
    errs = check(data, a.src)
    n = sum(len(g["rows"]) for g in data["groups"])
    if errs:
        print("FAIL (%d):" % len(errs))
        for e in errs:
            print("  " + e)
        return 1
    print("OK: %d rows in %d groups verified against %s" % (n, len(data["groups"]), a.src))
    if not a.check:
        with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
            f.write(emit(data))
        print("wrote " + OUT_PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
